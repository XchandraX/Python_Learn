# String dapat digabungkan menggunakan operator + atau
# diulang menggunakan operator *.

# Penggabungan (+)
print("Concatenation: ")
depan = "Budi"
belakang = "Santoso"
nama_lengkap = depan + " " + belakang 

print(nama_lengkap) # Output: Budi Santoso


# Repetisi (*)
print("\nRepetisi: ")
pesan = "Halo! " * 3 
print(pesan)    # Output: Halo! Halo! Halo!