# Membandingkan dua nilai. Hasil dari operasi perbandingan 
# selalu berupa nilai Boolean (True or False)


# Variable dasar
x = 22
y = 7


# Sama dengan (==) 
print(x == y)   # Output: False

# Tidak Sama dengan (!=)
print(x != y)   # Output: True

# Lebih besar dari (>)
print(x > y)    # Output: True

# Lebih kecil dari (<) 
print(x < y)    # Output: False

# Lebih besar dari atau sama dengan (>=)
print(x >= 9)   # Output: True

# Lebih kecil dari atau sama dengan (<=)
print(y <= 58)  # Output: True
