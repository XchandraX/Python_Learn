# Melakukan operasi matematika dasar
x = 10
y = 3

# Penjumlahan (+): 
print(x + y)    # Output: 13

# Pengurangan (-): 
print(x - y)    # Output: 7

# Perkalian (*): 
print(x * y)    # Output: 30

# Pembagian dengan desimal (/): 
print(x / y)    # Output: 3.333.....

# Pembagian bilangan bulat (//): - mengabaikan sisa desimal
print(x // y)   # Output: 3

# Modulo/Sisa bagi (%): - karena 10 bagi 3 sisa 1
print(x % y)    # Output: 1 

# Pangkat (**): 
print(x ** y)   # Output: 1000
