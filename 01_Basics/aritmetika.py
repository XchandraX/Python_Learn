x = 10
y = 3

print(x + y)    # Penjumlahan (13)
print(x - y)    # Pengurangan (7)
print(x * y)    # Perkalian (30)
print(x / y)    # Pembagian dengan desimal (3.333.....)
print(x // y)   # Pembagian bilangan bulat (3) - mengabaikan sisa desimal
print(x % y)    # Modulo/Sisa bagi (1) - karena 10 bagi 3 sisa 1
print(x ** y)   # Pangkat (1000) - 10 pangkat 3
