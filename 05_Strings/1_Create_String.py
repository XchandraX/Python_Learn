# Dibuat dengan mengapit karakter menggunakan tanda petik tunggal('),
# tanda petik ganda("), atau tanda petik tiga(''' atau """).

# Petik tunggal dan ganda
teks_1 = 'Halo'
print(teks_1)
teks_2 = "Python"
print(teks_2)

# Petik tiga (digunakan untuk teks multi-baris / docstring)
teks_multiline = """Ini adalah contoh string
yang terdiri dari beberapa baris
teks sekaligus."""
print(teks_multiline)