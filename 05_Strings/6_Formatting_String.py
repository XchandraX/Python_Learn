# Metode modern dan paling direkomendasikan untuk memasukkan
# variabel ke dalam string di Python adalah
# F-String

nama = "Andi"
umur = 20
harga = 12500.5

# f-string sederhana
print(f"Nama saya {nama} dan berumur {umur} tahun.")

# f-string dengan operasi/format angka
print(f"Harga setelah diskon: Rp {harga * 0.9:.2f}")
# Output: Harga setelah diskon: Rp 11250.45