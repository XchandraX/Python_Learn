# Mengabungkan atau membalikkan beberapa kondisi boolean.

# Operator And
"""
Mengembalikan Ture jika
    kedua kondisi bernilai True
"""
print((5 > 3) and (10 > 3)) # True


# Operator or
"""
mengembalikan True jika
    salah satu kondisi bernilai True
"""
print((5 > 10) or (10 > 0)) # True


# Operator not
"""
Membalikkan nilai logika
    (Ture menjadi False, dan sebaliknya)
"""
print(not(5>3)) # False
print(5>3)      # jika tanpa not hasilnya True