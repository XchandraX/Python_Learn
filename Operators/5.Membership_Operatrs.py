# Mengecek apaakh suata nilai atau elemen terdapat di dalam 
# sebuah urutan/koleksi 
# Seperti String, List, Tuple atau Set

"""
in: Mengembalikan True jika nilai ditemukan dalam urutan.

not in: Mengembalikan True jika nila tidak ditemukan dalam urutan.
"""

buah = ["apel", "pisang", "mangaa"]

print("pisang" in buah)     # Output: True
print('durian' not in buah) # Output: True
print("a" in "Python")      # Output: False
print("C" in "Chandra")     # Output: True