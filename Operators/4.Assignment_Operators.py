# Memberikan (assign) atau memperbarui nilai ke dalam variabel.

x = 10  # Penugasan dasar: memasukkan nilai 10 ke x
print(x)

x += 5  # Sama dengan: x = x + 5 
print(x)    # Output: x = 15

x -= 3  # Sama dengan: x = x - 3
print(x)    # Output: x = 12

x *= 2  # Sama dengan: x = x * 2
print(x)    # Output: x = 24

x /= 4  # Sama dengan: x = x / 4
print(x)    # Output: x = 6.0